from __future__ import annotations

from typing import Protocol


class PlateInputTarget(Protocol):
    """What a `PlateController` drives: a plate's focus and navigation (D8).
    The Qt adapter implements it over QLineEdits; a host may attach another."""

    @property
    def active_index(self) -> int | None: ...

    @property
    def system_keyboard_active(self) -> bool: ...

    def submit_character(self, character: str) -> None: ...
    def backspace_character(self) -> None: ...
    def focus_first_empty_slot(self) -> None: ...
    def focus_slot(self, index: int) -> None: ...
