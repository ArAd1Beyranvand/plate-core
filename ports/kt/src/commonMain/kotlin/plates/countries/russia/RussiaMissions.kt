/** The three-digit mission codes that open a diplomatic plate. Code `127` is refused: [name] throws for it. */
object RussiaMissions {
    /** The error every layer shows for a refused code. */
    const val notFound = "COUNTRY NOT FOUND"

    val refused: List<String> = listOf("127")

    /** The restriction on a diplomatic spec's `code` register. */
    val restriction: ValuesRestriction = ValuesRestriction(group = "code", values = refused, reason = notFound)

    fun isRefused(code: String): Boolean = refused.contains(code)

    /** The mission for [code], or null for a code the list does not have. Throws for a refused code. */
    fun name(code: String): String? {
        if (isRefused(code)) throw PlateRestrictionException(restriction)
        return missions[code]
    }

    /** Every listed code and its mission, refused codes excluded. */
    val all: Map<String, String> get() = missions

    fun captionOf(group: (String) -> String): String? {
        val code = group("code")
        return if (code.length == 3 && !isRefused(code)) missions[code] else null
    }

