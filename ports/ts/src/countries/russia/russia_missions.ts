const refused: readonly string[] = ['127'];
const isRefused = (code: string): boolean => refused.includes(code);

/** The three-digit mission codes that open a diplomatic plate.
 *
 * Code `127` is refused: `name` throws for it, and `restriction` carries it
 * into the diplomatic spec so core refuses it everywhere. */
export const RussiaMissions = {
  /** The error every layer shows for a refused code. */
  notFound: 'COUNTRY NOT FOUND',
  refused,
  /** The restriction on a diplomatic spec's `code` register. */
  restriction: new PlateRestriction('code', refused, 'COUNTRY NOT FOUND'),
  isRefused,

  /** The mission for `code`, or null for a code the list does not have.
   *
   * Throws PlateRestrictionException for a refused code: unlike an unknown
   * one, a refused code is never a lookup miss a caller may shrug off. */
  name(code: string): string | null {
    if (isRefused(code)) throw new PlateRestrictionException(RussiaMissions.restriction);
    return Object.hasOwn(missions, code) ? missions[code] : null;
  },

  /** Every listed code and its mission, refused codes excluded. */
  all: missions,

  captionOf(group: (key: string) => string): string | null {
    const code = group('code');
    return code.length === 3 && !isRefused(code) && Object.hasOwn(missions, code) ? missions[code] : null;
  },
};
