// D3 codegen: ports/data → src/countries/<country>/{data,themes,index}.ts, the lazy index, [D4-code] stubs and their tests.
// Run from ports/ts: node codegen/gen.mjs. Units that exist are never overwritten; tests always are.
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';

const ts = join(import.meta.dirname, '..');
const repo = join(ts, '../..');
const read = (p) => JSON.parse(readFileSync(p, 'utf8'));
const write = (p, s) => (mkdirSync(dirname(p), { recursive: true }), writeFileSync(p, s));
const header = (from) => `// Generated by codegen/gen.mjs from ${from}; do not edit.\n`;
const countryOf = (pkg) => pkg.slice(0, -'_plate'.length);
const vectors = (rel) => (existsSync(join(repo, 'ports/vectors', rel)) ? read(join(repo, 'ports/vectors', rel)).cases : []);

const alphabets = read(join(repo, 'ports/data/alphabets.json')).alphabets;
const packages = Object.keys(read(join(repo, 'ports/data/index.json')).packages).filter((p) => existsSync(join(repo, `ports/data/countries/${p}.json`)));

/** Dart files carrying `TODO(ts): [D4-code]`, the way portctl's plan.units() finds them. */
function dartUnits() {
  const out = [];
  const walk = (d) => {
    for (const e of readdirSync(d, { withFileTypes: true })) {
      const p = join(d, e.name);
      if (e.isDirectory()) walk(p);
      else if (p.endsWith('.dart') && readFileSync(p, 'utf8').includes('TODO(ts): [D4-code]')) out.push(relative(repo, p));
    }
  };
  for (const e of readdirSync(repo)) if (e.endsWith('_plate') && existsSync(join(repo, e, 'lib'))) walk(join(repo, e, 'lib'));
  return out.sort();
}

/** The constructor options a validator takes, typed from the args its vectors pass. */
function argsType(cls) {
  const cases = vectors(`validators/${cls}.json`).filter((c) => c.input.validator.class === cls);
  const fields = new Map();
  for (const c of cases) for (const [k, v] of Object.entries(c.input.validator.args ?? {})) {
    const t = v === null ? 'null' : Array.isArray(v) ? 'readonly unknown[]' : typeof v;
    fields.set(k, (fields.get(k) ?? new Set()).add(t));
  }
  if (!fields.size) return null;
  const opt = (k) => cases.some((c) => !(k in (c.input.validator.args ?? {})));
  return `{ ${[...fields].map(([k, t]) => `readonly ${k}${opt(k) ? '?' : ''}: ${[...t].join(' | ')}`).join('; ')} }`;
}

function validatorStub(classes) {
  const body = classes.map((c) => {
    const args = argsType(c);
    const ctor = args ? `  constructor(_o: ${args}) {}\n\n` : '';
    return `export class ${c} implements PlateValidator {\n${ctor}  validate(_entry: PlateEntry): PlateValidation {\n    throw new Error('not ported');\n  }\n}\n`;
  });
  return `import type { PlateEntry, PlateValidation, PlateValidator } from '../../core/validators/plate_validator';\n\n${body.join('\n')}`;
}

function resolverStub(names, resolvers) {
  const owners = Map.groupBy(names, (n) => n.split('.')[0]);
  const sig = { theme: '(_base: PlateTheme, _group: (key: string) => string): PlateTheme', label: '(_group: (key: string) => string): string | null' };
  const body = [...owners].map(([o, ns]) => `export const ${o} = {\n${ns.map((n) => `  ${n.split('.')[1]}${sig[resolvers[n].signature]} {\n    throw new Error('not ported');\n  },\n`).join('')}};\n`);
  const theme = names.some((n) => resolvers[n].signature === 'theme') ? `import type { PlateTheme } from '../../core/theme/plate_theme';\n\n` : '';
  return theme + body.join('\n');
}

const units = new Map(dartUnits().map((f) => [f, { pkg: f.split('/')[0], stem: f.split('/').pop().slice(0, -5), validators: [], resolvers: [] }]));
const datas = new Map(packages.map((p) => [p, read(join(repo, `ports/data/countries/${p}.json`))]));
for (const [file, u] of units) {
  const src = readFileSync(join(repo, file), 'utf8');
  for (const [, c] of src.matchAll(/^(?:final |base )?class ([A-Z]\w*)/gm)) if (vectors(`validators/${c}.json`).some((x) => x.input.validator.class === c)) u.validators.push(c);
  for (const [n, r] of Object.entries(datas.get(u.pkg)?.resolvers ?? {})) if (r.kind === 'code' && r.file === file) u.resolvers.push(n);
}

let stubs = 0;
for (const u of units.values()) {
  const country = countryOf(u.pkg);
  const unit = join(ts, `src/countries/${country}/${u.stem}.ts`);
  if (!existsSync(unit)) {
    write(unit, u.validators.length ? validatorStub(u.validators) : resolverStub(u.resolvers, datas.get(u.pkg).resolvers));
    stubs++;
  }
  const calls = [...(u.validators.length ? [`validatorVectors(unit, ${JSON.stringify(u.validators)});`] : []), ...(u.resolvers.length ? [`resolverVectors(unit, ${JSON.stringify(u.resolvers)});`] : [])];
  const imports = [u.validators.length && 'validatorVectors', u.resolvers.length && 'resolverVectors'].filter(Boolean).join(', ');
  write(join(ts, `test/countries/${country}/${u.stem}.test.ts`), `${header('ports/vectors')}import * as unit from '../../../src/countries/${country}/${u.stem}';\nimport { ${imports} } from '../harness';\n\n${calls.join('\n')}\n`);
}

for (const [pkg, d] of datas) {
  const country = countryOf(pkg);
  const dir = join(ts, `src/countries/${country}`);
  const slim = { package: pkg, alphabets: Object.fromEntries(d.alphabets.map((r) => [r, (({ names, ...a }) => a)(alphabets[r])])), countries: d.countries, themes: d.themes, specs: d.specs, resolvers: d.resolvers, assets: d.assets, gallery: d.gallery };
  write(join(dir, 'data.ts'), `${header(`ports/data/countries/${pkg}.json`)}import type { CountryData } from '../load';\n\nexport const data: CountryData = JSON.parse(${JSON.stringify(JSON.stringify(slim))});\n`);

  const named = Object.entries(d.themes).flatMap(([ref, t], i) => t.names.filter((n) => /^[A-Z]\w*\.\w+$/.test(n)).map((n) => [...n.split('.'), i, ref]));
  const owners = Map.groupBy(named, ([o]) => o);
  if (owners.size) {
    const refs = [...new Set(named.map(([, , i, ref]) => `const t${i} = themeOf(data.themes[${JSON.stringify(ref)}]);`))];
    const objs = [...owners].map(([o, fs]) => `export const ${o} = {\n${fs.map(([, f, i]) => `  ${f}: t${i},\n`).join('')}} as const;\n`);
    write(join(dir, 'themes.ts'), `${header(`ports/data/countries/${pkg}.json`)}import { themeOf } from '../load';\nimport { data } from './data';\n\n${refs.join('\n')}\n\n${objs.join('\n')}`);
  }

  const mine = [...units.values()].filter((u) => u.pkg === pkg);
  const noArgs = new Set(d.gallery.map((g) => g.validator).filter(Boolean));
  const imports = mine.map((u) => {
    const names = [...new Set([...u.validators.filter((c) => noArgs.has(c) && !argsType(c)), ...u.resolvers.map((n) => n.split('.')[0])])];
    return names.length ? `import { ${names.join(', ')} } from './${u.stem}';\n` : '';
  });
  const vs = mine.flatMap((u) => u.validators.filter((c) => noArgs.has(c) && !argsType(c)));
  const rs = mine.flatMap((u) => u.resolvers).map((n) => `${JSON.stringify(n)}: ${n}`);
  const code = [rs.length && `resolvers: { ${rs.join(', ')} }`, vs.length && `validators: { ${vs.join(', ')} }`].filter(Boolean).join(', ');
  write(join(dir, 'index.ts'), `${header(`ports/data/countries/${pkg}.json`)}import { loadCountry } from '../load';\nimport { data } from './data';\n${imports.join('')}\nexport default loadCountry(data${code ? `, { ${code} }` : ''});\n`);
}

const lazy = [...datas.keys()].map((p) => `  ${JSON.stringify(countryOf(p))}: () => import('./${countryOf(p)}/index').then((m) => m.default),\n`);
write(join(ts, 'src/countries/index.ts'), `${header('ports/data/index.json')}import type { LoadedCountry } from './load';\n\n/** Country id → its module, loaded on demand: no country imports another (W7). */\nexport const countries: Record<string, () => Promise<LoadedCountry>> = {\n${lazy.join('')}};\n`);
console.log(`codegen: ${datas.size} countries, ${units.size} units (${stubs} new stubs)`);
