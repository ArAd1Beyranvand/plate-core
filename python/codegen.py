"""Country codegen (D3): ports/data -> plates/countries/<country>/data.py, the index, unit stubs and unit tests.

Run from ports/py:  python3 codegen.py
Unit modules (`plates/countries/<country>/<stem>.py`) are written only when missing; they are hand-ported.
"""
from __future__ import annotations

import json
import keyword
import re
from pathlib import Path

from compact import compact_country

HERE = Path(__file__).resolve().parent
DATA = HERE.parent / "data"
VECTORS = HERE.parent / "vectors"
SRC = HERE.parent.parent  # the repo root, for the Dart sources
OUT = HERE / "plates" / "countries"
TESTS = HERE / "tests" / "countries"
HEADER = '"""Generated by ports/py/codegen.py from ports/data/{src}; do not edit."""\n'


def snake(k: str) -> str:
    return re.sub(r"[A-Z]", lambda m: "_" + m.group().lower(), k)


def data_module(d: dict, alphabets: dict, units: dict, src: str) -> str:
    """The country's `data` module: its compact data, built into specs by `plates.countries.load` on import."""
    slim = {"package": d["package"], "alphabets": {r: {k: v for k, v in alphabets[r].items() if k != "names"} for r in d["alphabets"]},
            **{k: d[k] for k in ("countries", "themes", "specs", "resolvers", "assets", "gallery")}}
    text = json.dumps(compact_country(slim), separators=(",", ":"), ensure_ascii=False)
    text = repr(text) if "'''" in text else f"r'''{text}'''"
    code = {k: f"{k.split('.')[0]}.{snake(k.split('.')[1])}" for k, r in d["resolvers"].items() if r["kind"] == "code"}
    imports = [f"from .{stem} import {', '.join(u['names'])}" for stem, u in units.items()]
    validators = ", ".join(f"{v['name']!r}: {v['name']}" for v in d["validators"])
    return (HEADER.format(src=src) + "from plates.countries.load import load_country\n" + "\n".join(imports) + "\n\n"
            + f"COUNTRIES, THEMES, SPECS, CODE_RENDER, GALLERY = load_country({text}, "
            + "{" + ", ".join(f"{k!r}: {v}" for k, v in code.items()) + "})\n"
            + f"VALIDATORS = {{{validators}}}\n")


def gate_group(dart: str, cls: str) -> str | None:
    m = re.search(rf"class {cls}\b.*?String get gateGroup\s*=>\s*'([^']*)'", dart, re.S)
    return m and m.group(1)


def vector_args(cls: str) -> dict | None:
    f = VECTORS / "validators" / f"{cls}.json"
    for c in json.loads(f.read_text(encoding="utf8"))["cases"] if f.exists() else ():
        if "args" in c["input"]["validator"]:
            return c["input"]["validator"]["args"]
    return None


def py_type(v) -> str:
    return {bool: "bool", int: "int", float: "float", str: "str", list: "tuple", dict: "dict"}.get(type(v), "object")


def validator_stub(v: dict, dart: str) -> str:
    cls, gated = v["name"], v["gated"]
    args = vector_args(cls)
    head = "@dataclass(frozen=True)\n" if args else ""
    fields = "".join(f"    {snake(k)}: {py_type(x)}\n" for k, x in (args or {}).items())
    if gated:
        gate = gate_group(dart, cls)
        gate = f"    gate_group = {gate!r}\n" if gate else (
            '    gate_group = ""  # computed in Dart: port the gateGroup getter\n\n'
            '    def validate(self, entry: PlateEntry) -> PlateValidation:\n'
            '        raise NotImplementedError("not ported")\n')
        return (f"{head}class {cls}(GatedPlateValidator):\n{fields}{chr(10) if fields else ''}{gate}\n"
                f"    def judge(self, entry: PlateEntry) -> PlateValidation:\n        raise NotImplementedError(\"not ported\")\n")
    return (f"{head}class {cls}:\n{fields}{chr(10) if fields else ''}"
            f"    def validate(self, entry: PlateEntry) -> PlateValidation:\n        raise NotImplementedError(\"not ported\")\n")


def resolver_stub(cls: str, members: list[tuple[str, str]]) -> str:
    out = f"class {cls}:\n"
    for member, signature in members:
        params = "group" if signature == "label" else "base, group"
        out += f"    @staticmethod\n    def {snake(member)}({params}):\n        raise NotImplementedError(\"not ported\")\n\n"
    return out.rstrip("\n") + "\n"


def unit_source(unit: dict) -> str:
    dart = (SRC / unit["file"]).read_text(encoding="utf8")
    head = '"""Port of {}. Hand-ported; codegen never overwrites this file."""\nfrom __future__ import annotations\n\n'
    imports = ""
    if any(v["args"] for v in unit["validators"]):
        imports += "from dataclasses import dataclass\n\n"
    if unit["validators"]:
        names = ["PlateEntry", "PlateValidation"] + (["GatedPlateValidator"] if any(v["gated"] for v in unit["validators"]) else [])
        imports += f"from plates.core.validators.plate_validator import {', '.join(sorted(names))}\n"
    classes = [validator_stub(v, dart) for v in unit["validators"]]
    classes += [resolver_stub(c, m) for c, m in unit["resolvers"].items()]
    return head.format(unit["file"]) + (imports + "\n\n" if imports else "") + "\n\n".join(classes)


def unit_test(country: str, stem: str, unit: dict) -> str:
    fns = []
    for v in unit["validators"]:
        fns.append(f"def test_{v['name']}():\n    check_validator(u.{v['name']})\n")
    for cls, members in unit["resolvers"].items():
        for member, _ in members:
            fns.append(f"def test_{cls}_{member.lstrip('_')}():\n    check_resolver({cls + '.' + member!r})\n")
    uses = ", ".join(n for n, on in (("check_resolver", unit["resolvers"]), ("check_validator", unit["validators"])) if on)
    return (f'"""Vectors for plates/countries/{country}/{stem}.py; generated by ports/py/codegen.py."""\n'
            f"{f'from plates.countries.{country} import {stem} as u' + chr(10) if unit['validators'] else ''}from tests.unit_vectors import {uses}\n\n\n"
            + "\n\n".join(fns))


def main() -> None:
    index = json.loads((DATA / "index.json").read_text(encoding="utf8"))["packages"]
    alphabets = json.loads((DATA / "alphabets.json").read_text(encoding="utf8"))["alphabets"]
    countries, stubs = {}, 0
    for f in sorted((DATA / "countries").glob("*.json")):
        d = json.loads(f.read_text(encoding="utf8"))
        pkg = d["package"]
        country = pkg.removesuffix("_plate")
        assert country.isidentifier() and not keyword.iskeyword(country), country
        units: dict[str, dict] = {}
        for v in d["validators"]:
            stem = Path(v["file"]).stem
            units.setdefault(stem, {"file": v["file"], "validators": [], "resolvers": {}, "names": []})
            units[stem]["validators"].append({**v, "args": vector_args(v["name"])})
            units[stem]["names"].append(v["name"])
        for key, r in d["resolvers"].items():
            if r["kind"] == "code":
                cls, member = key.split(".")
                stem = Path(r["file"]).stem
                u = units.setdefault(stem, {"file": r["file"], "validators": [], "resolvers": {}, "names": []})
                u["resolvers"].setdefault(cls, []).append((member, r["signature"]))
                if cls not in u["names"]:
                    u["names"].append(cls)
        assert "data" not in units and "tables" not in units, country
        cdir, tdir = OUT / country, TESTS / country
        cdir.mkdir(exist_ok=True)
        tdir.mkdir(exist_ok=True, parents=True)
        (cdir / "__init__.py").write_text(f'"""{country}: `data` holds the generated specs, the other modules the hand-ported units."""\n', encoding="utf8")
        (tdir / "__init__.py").write_text("", encoding="utf8")
        (cdir / "data.py").write_text(data_module(d, alphabets, units, f"countries/{f.name}"), encoding="utf8")
        for stem, unit in units.items():
            if not (cdir / f"{stem}.py").exists():
                (cdir / f"{stem}.py").write_text(unit_source(unit), encoding="utf8")
                stubs += 1
            (tdir / f"test_{stem}.py").write_text(unit_test(country, stem, unit), encoding="utf8")
        countries[country] = (pkg, index[pkg]["specs"])
    lines = ['"""Generated by ports/py/codegen.py: country id -> (package, spec ids). Nothing here imports a country."""',
             "from importlib import import_module", "", "COUNTRIES = {"]
    lines += [f"    {c!r}: ({p!r}, {tuple(s)!r})," for c, (p, s) in countries.items()] + ["}", "",
             "", "def load(country: str):", '    """The `data` module of one country, imported on demand."""',
             '    return import_module(f"{__name__}.{country}.data")', ""]
    (OUT / "__init__.py").write_text("\n".join(lines), encoding="utf8")
    print(f"{len(countries)} countries, {stubs} new stubs")


if __name__ == "__main__":
    main()
