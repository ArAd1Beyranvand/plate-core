/** Dart files carrying `TODO(ts): [D4-code]`, the way portctl's plan.units() finds them. */
function dartUnits() {
  const out = [];
  const walk = (d) => {
    for (const e of readdirSync(d, { withFileTypes: true })) {
      const p = join(d, e.name);
      if (e.isDirectory()) walk(p);
      else if (p.endsWith('.dart') && readFileSync(p, 'utf8').includes('TODO(ts): [D4-code]')) out.push(relative(repo, p));
    }
  };
  for (const e of readdirSync(repo)) if (e.endsWith('_plate') && existsSync(join(repo, e, 'lib'))) walk(join(repo, e, 'lib'));
  return out.sort();
}

/** A Dart type (`List<(int, int)>?`) as a tree: {name, args, nullable}; records are named `()`. */
function parseType(s) {
  let i = 0;
  const ws = () => { while (/\s/.test(s[i] ?? '')) i++; };
  const one = () => {
    ws();
    let t;
    if (s[i] === '(') {
      i++;
      t = { name: '()', args: list(')') };
    } else {
      const name = /^[\w.]+/.exec(s.slice(i))[0];
      i += name.length;
      ws();
      t = { name, args: s[i] === '<' ? (i++, list('>')) : [] };
    }
    ws();
    t.nullable = s[i] === '?' && !!++i;
    return t;
  };
  const list = (close) => {
    const out = [one()];
    for (ws(); s[i] === ','; ws()) i++, out.push(one());
    i++;
    return out;
  };
  return one();
}

/** The `final <Type> <names>;` fields declared in `src`, by name. */
function dartFields(src) {
  const out = new Map();
  for (const [, decl] of src.matchAll(/^ {2}final\s+([^;=]+);/gm)) {
    let depth = 0, j = 0;
    for (; j < decl.length && !(depth === 0 && /\s/.test(decl[j]) && j > 0); j++) depth += '<('.includes(decl[j]) ? 1 : '>)'.includes(decl[j]) ? -1 : 0;
    for (const n of decl.slice(j).split(',')) if (n.trim()) out.set(n.trim(), decl.slice(0, j).trim());
  }
  return out;
}

const scalars = { int: ['Int', 'int'], double: ['Double', 'dbl'], num: ['Double', 'dbl'], bool: ['Boolean', 'bool'], String: ['String', 'str'] };

/** A Kotlin type and the expression reading it from the JsonElement `v`; null for a type only a hand port knows. */
function ktOf(t, v, depth = 1) {
  const e = `e${depth}`;
  const inner = t.nullable ? `${e}0` : v;
  let r;
  if (scalars[t.name]) r = { type: scalars[t.name][0], read: `${inner}.${scalars[t.name][1]}()` };
  else if ((t.name === 'List' || t.name === 'Set') && t.args.length === 1) {
    const a = ktOf(t.args[0], e, depth + 1);
    r = a && { type: `${t.name}<${a.type}>`, read: `${inner}.list { ${e} -> ${a.read} }${t.name === 'Set' ? '.toSet()' : ''}` };
  } else if (t.name === 'Map' && t.args[0]?.name === 'String') {
    const a = ktOf(t.args[1], `${e}.at(1)`, depth + 1);
    r = a && { type: `Map<String, ${a.type}>`, read: `${inner}.list { ${e} -> ${e}.at(0).str() to ${a.read} }.toMap()` };
  } else if (t.name === '()' && (t.args.length === 2 || t.args.length === 3)) {
    const as = t.args.map((x, k) => ktOf(x, `${inner}.at(${k})`, depth + 1));
    const tuple = as.length === 2 ? 'Pair' : 'Triple';
    r = as.every(Boolean) && { type: `${tuple}<${as.map((a) => a.type).join(', ')}>`, read: `${tuple}(${as.map((a) => a.read).join(', ')})` };
  }
  if (!r || !t.nullable) return r || null;
  return { type: `${r.type}?`, read: `${v}.orNull { ${e}0 -> ${r.read} }` };
}

/** A JSON-only guess when the Dart field is inherited or declared elsewhere. */
function guess(values) {
  const nullable = values.some((x) => x === null);
  const vs = values.filter((x) => x !== null);
  const name = !vs.length ? null : vs.every(Number.isInteger) ? 'int' : vs.every((x) => typeof x === 'number') ? 'double'
    : vs.every((x) => typeof x === 'boolean') ? 'bool' : vs.every((x) => typeof x === 'string') ? 'String'
    : vs.every((x) => Array.isArray(x) && x.every((y) => typeof y === 'string')) ? 'List<String>' : null;
  return name && parseType(name + (nullable ? '?' : ''));
}

/** A validator class's constructor args, each {name, type, read}; null when one needs a hand-written factory. */
function argsOf(cls, src) {
  const cases = casesOf(cls);
  const keys = [...new Set(cases.flatMap((c) => Object.keys(c.input.validator.args ?? {})))];
  if (!keys.length) return [];
  const start = src.search(new RegExp(`^(?:final |base )?class ${cls}\\b`, 'm'));
  const own = dartFields(src.slice(start, src.indexOf('\n}', start)));
  const all = dartFields(src);
  const out = keys.map((k) => {
    const dart = own.get(k) ?? all.get(k);
    const t = dart ? parseType(dart) : guess(cases.map((c) => c.input.validator.args[k]));
    const r = t && ktOf(t, `a.getValue("${k}")`);
    return r && { name: k, ...r };
  });
  return out.every(Boolean) ? out : null;
}

function validatorStub(cls, args) {
  const params = args ? args.map((a) => `val ${id(a.name)}: ${a.type}`).join(', ') : '';
  const note = args ? '' : '// TODO(kt): the constructor of the Dart class; its vectors build it in the test\'s Args.kt.\n';
  return `${note}class ${cls}${params ? `(${params})` : ''} : PlateValidator {\n    override fun validate(entry: PlateEntry): PlateValidation = TODO("not ported")\n}\n`;
}

const sig = {
  theme: ['(base: PlateTheme, group: (String) -> String): PlateTheme', 'themeVectors'],
  label: ['(group: (String) -> String): String?', 'labelVectors'],
};

function resolverStub(names, resolvers) {
  const owners = Map.groupBy(names, (n) => n.split('.')[0]);
  return [...owners].map(([o, ns]) => `object ${o} {\n${ns.map((n) => `    fun ${n.split('.')[1]}${sig[resolvers[n].signature][0]} = TODO("not ported")\n`).join('')}}\n`);
}

function unitStub(u, country, resolvers) {
  const imports = [
    ...(u.validators.length ? ['plates.core.validators.PlateEntry', 'plates.core.validators.PlateValidation', 'plates.core.validators.PlateValidator'] : []),
    ...(u.resolvers.some((n) => resolvers[n].signature === 'theme') ? ['plates.core.theme.PlateTheme'] : []),
  ].sort();
  const body = [...u.validators.map((c) => validatorStub(c, u.args.get(c))), ...resolverStub(u.resolvers, resolvers)];
  return `package plates.countries.${country}\n\n${imports.map((i) => `import ${i}\n`).join('')}${imports.length ? '\n' : ''}${body.join('\n')}`;
}

function unitTest(u, country, resolvers) {
  const tests = [
    ...u.validators.map((c) => {
      const args = u.args.get(c);
      const make = !args ? `{ a -> ${camel(c)}Of(a) }` : args.length ? `{ a -> ${c}(${args.map((x) => `${id(x.name)} = ${x.read}`).join(', ')}) }` : `{ ${c}() }`;
      return `    @Test fun ${camel(c)}() = validatorVectors("${c}") ${make}\n`;
    }),
    ...u.resolvers.map((n) => `    @Test fun ${camel(n.replace(/\.(.)/, (_, x) => x.toUpperCase()))}() = ${sig[resolvers[n].signature][1]}("${n}", ${n.replace('.', '::')})\n`),
  ];
  const used = ['validatorVectors', 'labelVectors', 'themeVectors'].filter((f) => tests.some((t) => t.includes(`= ${f}(`)));
  const json = ['at', 'bool', 'dbl', 'int', 'list', 'orNull', 'str'].filter((h) => tests.some((t) => t.includes(`.${h}(`) || t.includes(`.${h} {`)));
  const imports = ['kotlin.test.Test', ...[...used, ...json].map((f) => `plates.countries.${f}`)].sort();
  return `${header('ports/vectors')}package plates.countries.${country}\n\n${imports.map((i) => `import ${i}\n`).join('')}\nclass ${u.Stem}Test {\n${tests.join('')}}\n`;
}

const units = new Map(dartUnits().map((f) => [f, { pkg: f.split('/')[0], stem: f.split('/').pop().slice(0, -5), validators: [], resolvers: [], args: new Map() }]));
const datas = new Map(packages.map((p) => [p, read(join(repo, `ports/data/countries/${p}.json`))]));
for (const [file, u] of units) {
  const src = readFileSync(join(repo, file), 'utf8');
  u.Stem = pascal(u.stem);
  for (const [, c] of src.matchAll(/^(?:final |base )?class ([A-Z]\w*)/gm)) if (casesOf(c).length) u.validators.push(c), u.args.set(c, argsOf(c, src));
  for (const [n, r] of Object.entries(datas.get(u.pkg)?.resolvers ?? {})) if (r.kind === 'code' && r.file === file) u.resolvers.push(n);
}

let stubs = 0;
for (const u of units.values()) {
  const country = countryOf(u.pkg);
  const resolvers = datas.get(u.pkg)?.resolvers ?? {};
  const unit = join(main, country, `${u.Stem}.kt`);
  if (!existsSync(unit)) write(unit, unitStub(u, country, resolvers)), stubs++;
  const hooks = u.validators.filter((c) => !u.args.get(c));
  const argsFile = join(test, country, `${u.Stem}Args.kt`);
  if (hooks.length && !existsSync(argsFile)) {
    const fns = hooks.map((c) => `/** Builds the [${c}] its vectors describe in [a] (\`input.validator.args\`). */\ninternal fun ${camel(c)}Of(a: JsonObject): ${c} = TODO("not ported")\n`);
    write(argsFile, `package plates.countries.${country}\n\nimport kotlinx.serialization.json.JsonObject\n\n${fns.join('\n')}`);
  }
  if (u.validators.length || u.resolvers.length) write(join(test, country, `${u.Stem}Test.kt`), unitTest(u, country, resolvers));
}

/** JSON as Kotlin string literals; a JVM string constant holds at most 65535 bytes of modified UTF-8. */
function literal(json) {
  const parts = [];
  for (let i = 0; i < json.length;) {
    let j = Math.min(i + 16000, json.length);
    if (j < json.length && /[\ud800-\udbff]/.test(json[j - 1])) j--;
    parts.push(str(json.slice(i, j)));
    i = j;
  }
  return parts.length === 1 ? parts[0] : `arrayOf(\n${parts.map((p) => `    ${p},\n`).join('')}).joinToString("")`;
}

