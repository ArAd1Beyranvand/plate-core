#!/usr/bin/env python3
"""Generates plate_number_holder/test/port_export_names.g.dart for the D3 exporter.

Flutter has no mirrors, so the exporter (test/port_export_test.dart) cannot find
a package's specs by itself. This scans plate_alphabet and every `*_plate`
package the holder depends on for public `static final|const` fields and static
getters of type PlateSpec, PlateAlphabet, PlateCountry and PlateTheme on public
classes, and emits package -> Dart name -> value. Each barrel is imported under
its package name as prefix, so equal class names in two packages cannot clash.

It also lists every function shaped like a PlateLabelResolver or
PlateThemeResolver with the `TODO(ts): [D4-table|D4-code]` tag above it (empty
when untagged) and its file, plus the tear-off where it is public, so the
exporter can tell a table from logic. Closures print only their method name.

Names the analyzer rejects (classes a barrel does not export) are dropped, so the
output always compiles; they are printed. Run from anywhere:

    python3 tools/port_export_names.py
"""
import pathlib
import re
import subprocess

ROOT = pathlib.Path(__file__).resolve().parent.parent
APP = ROOT / 'plate_number_holder'
OUT = APP / 'test' / 'port_export_names.g.dart'
TYPES = 'PlateSpec|PlateAlphabet|PlateCountry|PlateTheme'

CLASS = re.compile(r'^(?:(?:abstract|sealed|base|final|interface|mixin) )*class (\w+)', re.M)
MEMBER = re.compile(r'(@Deprecated\([^;]*?\)\s*)?^\s+static (?:(?:final|const) (%s)\?? (\w+)\s*=|(%s)\?? get (\w+))'
                    % (TYPES, TYPES), re.M)
RESOLVER = re.compile(r'^(\s*)(?:static )?(?:String\?|PlateTheme) (\w+)\(\s*(?:PlateTheme \w+,\s*)?'
                      r'String Function\(String(?: \w+)?\) \w+,?\s*\)', re.M)
TAG = re.compile(r'TODO\(ts\): \[(D4-table|D4-code)\]')


def packages():
    text = (APP / 'pubspec.yaml').read_text()
    deps = sorted(set(re.findall(r'^  (\w+_plate):\n    path:', text, re.M)))
    return ['plate_alphabet'] + deps


def names(pkg):
    out = []
    for f in sorted((ROOT / pkg / 'lib').rglob('*.dart')):
        text = f.read_text()
        classes = [(m.start(), m.group(1)) for m in CLASS.finditer(text)]
        for m in MEMBER.finditer(text):
            owner = [c for pos, c in classes if pos < m.start()]
            name = m.group(3) or m.group(5)
            if m.group(1) or not owner or owner[-1].startswith('_') or name.startswith('_'):
                continue
            out.append(f'{owner[-1]}.{name}')
    return list(dict.fromkeys(out))


def resolvers(pkg):
    """(name, tag, file, public) per resolver-shaped function; name is Class.method or a top-level name."""
    out = []
    for f in sorted((ROOT / pkg / 'lib').rglob('*.dart')):
        text = f.read_text()
        classes = [(m.start(), m.group(1)) for m in CLASS.finditer(text)]
        for m in RESOLVER.finditer(text):
            owner = [c for pos, c in classes if pos < m.start()] if m.group(1) else []
            name = f'{owner[-1]}.{m.group(2)}' if owner else m.group(2)
            above = []
            for line in reversed(text[:m.start()].splitlines()):
                if not line.strip().startswith(('//', '@')):
                    break
                above.append(line)
            tag = next((t.group(1) for t in map(TAG.search, above) if t), '')
            public = not any(part.startswith('_') for part in name.split('.'))
            out.append((name, tag, str(f.relative_to(ROOT)), public))
    return out


def render(entries, fns):
    lines = ['// GENERATED by tools/port_export_names.py. Do not edit.',
             '// ignore_for_file: directives_ordering, depend_on_referenced_packages', '']
    lines += [f"import 'package:{p}/{p}.dart' as {p};" for p in entries]
    lines += ['', '/// Package -> Dart name -> every public static spec, alphabet, country and theme.',
              'final Map<String, Map<String, Object>> portExportNames = <String, Map<String, Object>>{']
    for p, ns in entries.items():
        lines.append(f"  '{p}': <String, Object>{{")
        lines += [f"    '{n}': {p}.{n}," for n in ns]
        lines.append('  },')
    lines += ['};', '',
              '/// Package -> resolver name -> its D4 tag (\'\' when untagged), file and public tear-off.',
              'final Map<String, Map<String, ({String tag, String file, Function? fn})>> portExportResolvers =',
              '    <String, Map<String, ({String tag, String file, Function? fn})>>{']
    for p, rs in fns.items():
        lines.append(f"  '{p}': <String, ({{String tag, String file, Function? fn}})>{{")
        lines += [f"    '{n}': (tag: '{t}', file: '{f}', fn: {f'{p}.{n}' if pub else 'null'}),"
                  for n, t, f, pub in rs]
        lines.append('  },')
    lines += ['};', '']
    return '\n'.join(lines)


def main():
    entries = {p: names(p) for p in packages()}
    fns = {p: resolvers(p) for p in packages()}
    dropped = []
    for _ in range(5):
        OUT.write_text(render(entries, fns))
        res = subprocess.run(['dart', 'analyze', str(OUT)], cwd=APP, capture_output=True, text=True)
        bad = {int(m.group(1)) for m in re.finditer(r'^\s*error - \S+:(\d+):\d+', res.stdout, re.M)}
        if not bad:
            break
        text = OUT.read_text().splitlines()
        drop = {re.sub(r"^'([^']+)'.*", r'\1', text[i - 1].strip()) for i in bad}
        dropped += sorted(drop)
        entries = {p: [n for n in ns if n not in drop] for p, ns in entries.items()}
        fns = {p: [(n, t, f, pub and n not in drop) for n, t, f, pub in rs] for p, rs in fns.items()}
    else:
        raise SystemExit(f'still failing to analyze:\n{res.stdout}')
    for n in dropped:
        print(f'  dropped (not exported): {n}')
    print(f'{sum(map(len, entries.values()))} names, {sum(map(len, fns.values()))} resolvers, {len(entries)} packages -> {OUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
